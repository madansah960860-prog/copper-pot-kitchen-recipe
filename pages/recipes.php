      <div>
        <h2>Why only six</h2>
        <p>Because each of these took three or four full cooks to get right, plus a test by
          somebody working only from the written draft, and that is roughly a fortnight of
          evenings per recipe. Publishing forty a year would mean publishing thirty-four that
          had been cooked once.</p>
        <p>New recipes go up when they are finished. There is no schedule, no weekly slot and
          nothing published to fill a gap. If nothing appears for four months, it is because
          nothing was ready.</p>
      </div>
      <div>
        <h2>What will not appear here</h2>
        <p>Anything under thirty minutes, which other sites do better. Baking, because it is
          a different discipline and there are people who do it properly. Anything described
          as healthy, clean or guilt-free, which are marketing words rather than cooking
          ones.</p>
        <p>And no sponsored recipes, ever. Nothing on this site was written because somebody
          paid for it, and the <a href="../policies/advertising-disclosure.php">advertising
          disclosure</a> explains the whole commercial arrangement, which is short.</p>
