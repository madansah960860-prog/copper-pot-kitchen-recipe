        <h2>The three things that usually went wrong</h2>
        <p><strong>The pan was too small.</strong> This is the single most common cause of a
          braise that came out thin or a batch of onions that stewed instead of browning. A
          crowded pan traps steam, and steam is the enemy of every recipe on this site. If a
          recipe says wide, it means wider than the one you were about to reach for.</p>
        <p><strong>The oven is not the temperature it says.</strong> Most domestic ovens are
          out by fifteen to twenty-five degrees and many are out by more. An oven thermometer
          costs very little and will explain years of confusion. Mine runs cool, which is why
          every temperature here comes with a visual cue as well as a number.</p>
        <p><strong>The cut was leaner than the one specified.</strong> Braising steak instead
          of shin, leg instead of shoulder, breast instead of thigh. Lean cuts have no
          collagen to turn into gelatine, so they go dry rather than tender however long you
          give them. This is not a technique problem and no amount of extra time fixes it.</p>
      </div>
      <div>
        <h2>Things I cannot help with</h2>
        <p>Substituting a cut I have not cooked. I will tell you honestly that I do not know,
          rather than guess, because a guess about a braise costs you four hours and a piece
          of meat.</p>
        <p>Scaling a recipe up by more than double. Braises do not scale linearly: the surface
          area to volume ratio changes, evaporation changes, and the timings stop applying. If
          you are cooking for twenty, cook two pots.</p>
        <p>Anything dietary or medical. I am a cook, not a dietitian, and the
          <a href="../policies/disclaimer.php">disclaimer</a> sets out that position
          in more formal language. If you have an allergy, read the labels rather than
          trusting my allergen note, which describes ingredients as written rather than the
          packet in your hand.</p>
        <p>Slow cooker and pressure cooker conversions for these particular recipes. Both
          appliances work well and I have not tested these six in either, so anything I told
          you would be invented.</p>
      </div>
