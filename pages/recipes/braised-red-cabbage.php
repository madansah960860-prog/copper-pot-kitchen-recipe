      <div>
        <h2>Method</h2>
        <ol class="method">
      <li><div><p>Heat the oven to 325&#176;F. Melt the butter in a large ovenproof casserole over medium heat and cook the onion with a pinch of the salt for eight minutes until soft but not colored.</p></div></li>
      <li><div><p>Add the grated apple and cook for two more minutes.</p></div></li>
      <li><div><p>Add the cabbage in two or three additions, stirring each in as it collapses enough to make room for the next. It looks like far too much and it will not be.</p></div></li>
      <li><div><p>Add the vinegar, wine, sugar, juniper, bay, cloves, the remaining salt and a good grinding of pepper. Stir thoroughly so the vinegar reaches everything; this is what keeps the color.</p></div></li>
      <li><div><p>Bring to a simmer on the stovetop, put the lid on, and transfer to the oven.</p></div></li>
      <li><div><p>Cook for one hour and fifteen minutes to one hour and thirty minutes, stirring once halfway. It is ready when the cabbage is completely tender with no squeak against the teeth, and the liquid has reduced to a glossy few spoonfuls at the bottom.</p></div></li>
      <li><div><p>If there is still a pool of liquid, put it back on the stovetop uncovered and boil hard for five minutes, stirring, until it has gone.</p></div></li>
      <li><div><p>Taste. It should be sweet, sharp and savory in roughly that order. Add a splash more vinegar if it is flat, a pinch more sugar if it is aggressive, and more salt than you think.</p></div></li>
      <li><div><p>Fish out the bay leaf and the whole cloves if you used them. Serve hot, or cool and refrigerate for tomorrow, which is what we would do.</p></div></li>
        </ol>

        <h2>Notes</h2>
        <div class="note">
          <h3>Allergens</h3>
          <p>Contains milk (butter); use duck fat or oil to avoid it. Contains sulphites from the wine and vinegar. Free from wheat, nuts, egg and soy as written.</p>
          <p><strong>Check every label yourself.</strong> Formulations change and this note
            describes the ingredients as written, not the packet in your hand.</p>
        </div>
        <div class="note mt5">
          <h3>Storage and reheating</h3>
          <p>Refrigerate within two hours for up to five days and it improves for the first three of them. Freezes for three months. Reheat covered in a low oven or gently on the stovetop with a splash of water until piping hot.</p>
        </div>
        <div class="note mt5">
          <h3>Swaps that work</h3>
          <p>Pear instead of apple. Balsamic instead of red wine vinegar, using slightly less sugar. A strip of orange zest added with the bay is very good. Bacon fried off at the start turns it into something you could eat on its own.</p>
        </div>

