    <div class="why">
      <h3>Why it works</h3>
      <p>The vinegar is doing chemistry, not just seasoning. Red cabbage gets its color from anthocyanins, which are pH-sensitive pigments: acidic and they stay a bright red-purple, alkaline and they turn a dismal gray-blue. Cook red cabbage in plain water and you get the gray version. The vinegar and the apple keep the pot on the acid side, which is why this recipe comes out the color it does.</p>
    </div>
  </div>
</section>

