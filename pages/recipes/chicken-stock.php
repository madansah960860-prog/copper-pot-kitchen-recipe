    <div class="why">
      <h3>Why it works</h3>
      <p>Two rules make stock, and everything else is detail. The first is never to let it boil: a rolling boil emulsifies fat and breaks up proteins, which is exactly how you get cloudy, greasy stock. A bare simmer with the occasional lazy bubble keeps it clear. The second is to use wings, feet or a carcass rather than breast meat, because what you are extracting is collagen from joints and connective tissue. Good stock sets to a wobble in the refrigerator. If yours does not, you needed more wings and less water.</p>
    </div>
