      <div>
        <h2>Method</h2>
        <ol class="method">
      <li><div><p>If you are using raw wings, and this makes a better stock, roast them at 425&#176;F for thirty minutes until well browned first. Carcasses from a roast bird are already browned and go straight in.</p></div></li>
      <li><div><p>Put the bones in your largest pot and cover with the cold water. Cold, not hot: starting cold draws proteins out slowly and they coagulate into a scum you can remove, rather than dispersing into the liquid.</p></div></li>
      <li><div><p>Bring very slowly to a bare simmer over medium-low heat. This should take twenty minutes or more. Do not walk away for the last five.</p></div></li>
      <li><div><p>As it comes up to temperature, a gray foam will gather at the edges. Skim it off with a spoon and discard. Do this two or three times over the first fifteen minutes. This is the whole secret to clear stock.</p></div></li>
      <li><div><p>Once the scum has stopped forming, add the vegetables, bay, peppercorns, parsley and thyme. Do not add salt. Stock gets reduced later and salting now will concentrate into something inedible.</p></div></li>
      <li><div><p>Adjust the heat until the surface barely moves: one lazy bubble every second or two. If it boils, the stock will go cloudy and you cannot un-cloud it. A heat diffuser or the smallest burner helps.</p></div></li>
      <li><div><p>Simmer uncovered, or with the lid ajar, for four hours. Top up with boiling water if the bones become exposed. Longer is not better; past about five hours the flavor starts to go flat and slightly bitter.</p></div></li>
      <li><div><p>Strain through a fine sieve into a bowl, pressing nothing. Pressing the solids pushes cloudiness through. Discard the bones and vegetables, which have given everything they have.</p></div></li>
      <li><div><p>Cool quickly. Stand the bowl in a sink of cold water and stir occasionally; you want it below 40&#176;F within four hours, and quicker is better. Refrigerate overnight.</p></div></li>
      <li><div><p>The next morning, lift off the solid fat cap with a spoon and keep it for roasting potatoes. The stock underneath should be set to a soft jelly. If it is liquid, it is still perfectly good stock and you simply used more water than bones.</p></div></li>
        </ol>

        <h2>Notes</h2>
        <div class="note">
          <h3>Allergens</h3>
          <p>Contains celery. Free from the other major allergens as written. If you add a stock cube to boost it, which we would not, check that label carefully.</p>
          <p><strong>Check every label yourself.</strong> Formulations change and this note
            describes the ingredients as written, not the packet in your hand.</p>
        </div>
        <div class="note mt5">
          <h3>Storage and reheating</h3>
          <p>Four days in the refrigerator with the fat cap left on, which seals it. Freezes for six months; freeze in 250 ml portions and in an ice cube tray for the tablespoon you need to finish a pan sauce. Reheat to a full boil before use.</p>
        </div>
        <div class="note mt5">
          <h3>Swaps that work</h3>
          <p>Roast the bones for a darker, deeper stock. Add a parmesan rind for savory depth. Leave out the carrot if you want something less sweet for a risotto. Never add salt at this stage, whatever the reason.</p>
        </div>

