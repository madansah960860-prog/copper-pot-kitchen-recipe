    <div class="why">
      <h3>Why it works</h3>
      <p>Two things. The first is that the marinade does less than the books claim: wine penetrates meat by a few millimeters at most overnight, so the real reason to marinate is that it flavors the braising liquid, not the chicken. The second is that the garnish of bacon, mushrooms and onions must be cooked separately and added at the end. Cook them in the braise from the start and they turn to mush and release water into a sauce you are trying to concentrate.</p>
    </div>
  </div>
</section>

