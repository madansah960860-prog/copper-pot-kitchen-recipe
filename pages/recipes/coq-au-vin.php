          is the direction that survives.</p>
      </aside>
      <div>
        <h2>Method</h2>
        <ol class="method">
      <li><div><p>The night before, if you can, put the chicken legs in a bowl with the wine, the chopped onion and carrot, the garlic, bay and thyme. Cover and refrigerate. If you cannot, an hour at room temperature does most of the job.</p></div></li>
      <li><div><p>Lift the chicken out and dry each piece thoroughly with paper towels. Strain the marinade, keeping both the liquid and the vegetables. Season the chicken with the salt.</p></div></li>
      <li><div><p>Heat the oil in a wide casserole over medium-high heat. Brown the legs skin side down for six or seven minutes without moving them, then two minutes on the other side. Work in two batches. Set aside.</p></div></li>
      <li><div><p>Pour off all but two tablespoons of the fat. Add the strained marinade vegetables and cook over medium heat for eight minutes until soft and starting to color.</p></div></li>
      <li><div><p>Stir in the tomato paste and cook for two minutes, then scatter over the flour and stir for another two. The flour needs to lose its raw taste and it will thicken the sauce as the braise goes on.</p></div></li>
      <li><div><p>Pour in the reserved wine, scraping the bottom hard. Bring to a boil and let it bubble for five minutes. Add the stock, bay and thyme, and return the chicken skin side up. The liquid should come about three quarters of the way up.</p></div></li>
      <li><div><p>Cover and cook at a bare simmer, either on the lowest stovetop heat or in a 325&#176;F oven, for one hour and fifteen minutes, until the meat pulls easily from the bone.</p></div></li>
      <li><div><p>While that happens, make the garnish. Fry the bacon in a dry pan over medium heat until the fat renders and it is crisp, about eight minutes. Lift it out. Brown the onions in the bacon fat for ten minutes, turning, until golden all over, and lift them out. Add the butter and fry the mushrooms hard for five or six minutes until deeply browned. Season them and set everything aside together.</p></div></li>
      <li><div><p>Lift the chicken out of the braise onto a plate. Strain the sauce into a clean pan, pressing the vegetables firmly to get everything out of them, then discard the solids.</p></div></li>
      <li><div><p>Boil the sauce hard for eight to twelve minutes until it coats the back of a spoon and you have roughly 400 ml left. This step is where the dish is either good or thin.</p></div></li>
      <li><div><p>Return the chicken to the sauce with the bacon, onions and mushrooms. Simmer together for five minutes so everything warms through and the garnish takes on some of the sauce. Taste and season. Scatter with parsley.</p></div></li>
        </ol>

        <h2>Notes</h2>
        <div class="note">
          <h3>Allergens</h3>
          <p>Contains wheat (flour) and milk (butter). May contain sulphites from the wine. Check the bacon, which often contains sugar and sometimes milk proteins, and the stock.</p>
          <p><strong>Check every label yourself.</strong> Formulations change and this note
            describes the ingredients as written, not the packet in your hand.</p>
        </div>
        <div class="note mt5">
          <h3>Storage and reheating</h3>
          <p>Refrigerate within two hours for up to three days and reheat gently to a full simmer. Freezes for two months, though the mushrooms soften. Better on the second day, as almost all braises are.</p>
        </div>
        <div class="note mt5">
          <h3>Swaps that work</h3>
          <p>White wine makes coq au vin jaune, which is excellent and a different dish. Use rabbit if you can get it. Leave the bacon out and double the mushrooms for a vegetarian-adjacent version, though at that point call it something else.</p>
        </div>

