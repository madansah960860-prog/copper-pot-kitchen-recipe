<section class="band band--tight">
  <div class="wrap">
    <div class="why">
      <h3>Why it works</h3>
      <p>Shin is a hard-working muscle, which means collagen, which means gelatine once it has spent long enough above about 160&#176;F in liquid. Gelatine is what makes a sauce cling to pasta instead of sliding off it, and it is why this ragu needs no cream, no butter finish and no cornflour. Brown the meat properly and take the time on the soffritto: those two steps are the whole difference between this and a ground meat sauce.</p>
    </div>
  </div>
</section>

