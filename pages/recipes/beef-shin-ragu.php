      <li><span class="qty">100 g<small>2 sticks</small></span><span>celery, finely diced</span></li>
      <li><span class="qty">4 cloves</span><span>garlic, sliced</span></li>
      <li><span class="qty">2 tbsp</span><span>tomato paste</span></li>
      <li><span class="qty">250 ml<small>1 cup</small></span><span>red wine, something you would drink</span></li>
      <li><span class="qty">400 g<small>1 can (14 oz)</small></span><span>whole plum tomatoes, crushed by hand</span></li>
