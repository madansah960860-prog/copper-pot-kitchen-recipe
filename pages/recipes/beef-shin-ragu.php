    <h3>To serve</h3>
    <ul>
      <li><span class="qty">500 g<small>1 lb</small></span><span>pappardelle or tagliatelle</span></li>
      <li><span class="qty">60 g<small>2/3 cup</small></span><span>Parmesan, finely grated</span></li>
      <li><span class="qty">2 tbsp</span><span>flat-leaf parsley, chopped</span></li>
    </ul>
        <p class="ui mt4">Weights are what we actually used. Cup
          measures are converted from those weights rather than the other way round, which
          is the direction that survives.</p>
      </aside>
      <div>
        <h2>Method</h2>
        <ol class="method">
      <li><div><p>Heat the oven to 300&#176;F. Pat the beef dry with paper towels and season it all over with the salt and plenty of pepper. Dry meat browns; wet meat steams, and the difference is the entire flavor of the finished sauce.</p></div></li>
      <li><div><p>Heat the oil in a heavy casserole over medium-high heat until it shimmers. Brown the beef in two or three batches, giving each piece three or four minutes a side without moving it. Do not crowd the pan. This takes about fifteen minutes in total and it is the step people rush. Set the browned pieces aside on a plate.</p></div></li>
      <li><div><p>Turn the heat down to medium-low. Add the onion, carrot and celery to the same pot with a pinch of salt and cook for twelve to fifteen minutes, stirring now and then, until everything is soft and the onion has gone translucent and slightly golden. Scrape the browned bits off the bottom as you go.</p></div></li>
      <li><div><p>Add the garlic and cook for one minute, then the tomato paste. Cook the paste for two minutes, stirring, until it darkens from bright red to brick. This removes the raw canned edge and is worth the two minutes.</p></div></li>
      <li><div><p>Pour in the wine, turn the heat up, and let it bubble hard for three or four minutes until the smell of alcohol has gone and the liquid has reduced by about half.</p></div></li>
      <li><div><p>Add the tomatoes, stock, bay, rosemary and orange zest. Return the beef and any juices from the plate. The liquid should come about two thirds of the way up the meat; add a splash of water if it does not.</p></div></li>
      <li><div><p>Bring to a bare simmer on the stovetop, put the lid on, and transfer to the oven. Cook for three and a half to four hours. Check once at the two-hour mark to make sure it is barely bubbling rather than boiling; if it is, drop the oven by 25 degrees.</p></div></li>
      <li><div><p>It is done when a piece of shin falls apart under a fork with no resistance at all. If there is any resistance, give it another thirty minutes. This is not a recipe that can be hurried and undercooked shin is unpleasantly chewy.</p></div></li>
      <li><div><p>Lift out the meat, discard the bones, bay, rosemary and orange zest, and shred the beef coarsely with two forks. Skim the fat from the surface of the sauce with a spoon; there will be a good amount and you want most of it gone.</p></div></li>
      <li><div><p>If the sauce looks loose, simmer it uncovered for ten or fifteen minutes. Return the meat, taste, and season. It will almost certainly want more salt than you expect.</p></div></li>
      <li><div><p>Cook the pasta one minute short of the packet time. Drain it, keeping a cup of the water, and turn it through the ragu in the pot over low heat for a minute, adding splashes of pasta water until the sauce coats every strand. Serve with the Parmesan and parsley.</p></div></li>
        </ol>

        <h2>Notes</h2>
        <div class="note">
          <h3>Allergens</h3>
          <p>Contains wheat (pasta) and milk (Parmesan). The ragu itself is free of both. Check the label on your stock, which frequently contains celery, wheat or soy, and on the wine, which may be fined with egg or fish products.</p>
          <p><strong>Check every label yourself.</strong> Formulations change and this note
            describes the ingredients as written, not the packet in your hand.</p>
        </div>
        <div class="note mt5">
          <h3>Storage and reheating</h3>
          <p>Cools and keeps better than almost anything. Refrigerate within two hours, in a sealed container, for up to four days; it is noticeably better on day two. Freezes for three months. Reheat gently on the stovetop with a splash of water until piping hot throughout.</p>
        </div>
        <div class="note mt5">
          <h3>Swaps that work</h3>
          <p>Beef cheek works and is arguably better. Oxtail works and takes another hour. Lamb shoulder works and wants the rosemary doubled. Do not use a lean cut; there is nothing in it to turn into sauce.</p>
        </div>

