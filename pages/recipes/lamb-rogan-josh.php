      <div>
        <h2>Method</h2>
        <ol class="method">
      <li><div><p>Pat the lamb dry. Heat two tablespoons of the ghee in a heavy pot over medium-high heat and brown the lamb in two batches, about four minutes a batch. Set aside.</p></div></li>
      <li><div><p>Add the remaining ghee and the sliced onions to the pot with a pinch of the salt. Cook over medium heat for eighteen to twenty minutes, stirring often, until deep golden brown. This is a long time and it is not optional; pale onions make a pale curry.</p></div></li>
      <li><div><p>Add the garlic and ginger pastes. Fry for two minutes until the raw smell goes.</p></div></li>
      <li><div><p>Turn the heat down to low. Add the Kashmiri chilli, fennel, coriander, cumin, ground cardamom and asafoetida. Fry for sixty to ninety seconds, stirring constantly. Ground spices burn in seconds at this stage, so keep the heat low and keep moving.</p></div></li>
      <li><div><p>Take the pot off the heat for a moment and let it cool slightly, then add the yogurt one spoonful at a time, stirring hard after each. Adding it all at once, or to a very hot pot, will split it.</p></div></li>
      <li><div><p>Return to medium heat and cook, stirring, for eight to ten minutes until the mixture thickens and you can see oil separating out around the edges of the pan. This is the step that makes the dish. Do not move on until you see it.</p></div></li>
      <li><div><p>Return the lamb with any juices. Add the bay, cardamom pods, cinnamon, the rest of the salt and the water. Stir well.</p></div></li>
      <li><div><p>Cover and cook at the barest simmer for one hour and forty-five minutes to two hours, stirring every half hour and adding a splash of water if it looks like catching. The lamb should be completely tender and the sauce should be thick enough to coat it.</p></div></li>
      <li><div><p>Uncover for the last twenty minutes if the sauce is looser than you want. Fish out the cinnamon stick and bay leaves.</p></div></li>
      <li><div><p>Take off the heat, stir in the garam masala, and let it sit with the lid on for ten minutes before serving. Taste for salt. Serve with plain rice and, if you like, yogurt.</p></div></li>
        </ol>

        <h2>Notes</h2>
        <div class="note">
          <h3>Allergens</h3>
          <p>Contains milk (yogurt, ghee). Asafoetida is very often blended with wheat flour, so check that label if you are avoiding gluten. Free from nuts as written.</p>
          <p><strong>Check every label yourself.</strong> Formulations change and this note
            describes the ingredients as written, not the packet in your hand.</p>
        </div>
        <div class="note mt5">
          <h3>Storage and reheating</h3>
          <p>Refrigerate within two hours for up to three days; the flavor improves considerably overnight. Freezes for three months. Reheat gently on the stovetop with a splash of water until piping hot throughout.</p>
        </div>
        <div class="note mt5">
          <h3>Swaps that work</h3>
          <p>Goat is traditional in Kashmir and takes another forty-five minutes. Lamb neck works very well and is cheaper than shoulder. Paprika plus a pinch of hot chilli approximates Kashmiri chilli for color if you cannot find it, though the flavor is not the same.</p>
        </div>

