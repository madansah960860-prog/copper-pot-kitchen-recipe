    <div class="why">
      <h3>Why it works</h3>
      <p>Rogan josh means, roughly, cooked in oil at intense heat, and the technique that gives the dish its name is bhunao: frying the spices and onion base in a generous amount of fat until the oil visibly separates and pools at the edges. That separation is not a flaw, it is the signal that the water has driven off and the spices are frying rather than stewing. Stop before it happens and the curry tastes raw and thin no matter how long you simmer it afterward.</p>
    </div>
  </div>
</section>

