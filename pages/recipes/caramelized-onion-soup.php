      <li><span class="qty">2 sprigs</span><span>thyme</span></li>
      <li><span class="qty">100 ml<small>1/3 cup plus 1 tbsp</small></span><span>dry sherry or dry white wine</span></li>
      <li><span class="qty">1.2 liters<small>5 cups</small></span><span>good beef or chicken stock</span></li>
