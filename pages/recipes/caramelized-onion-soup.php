    <div class="why">
      <h3>Why it works</h3>
      <p>What is happening for those ninety minutes is two separate chemistries. The Maillard reaction browns the proteins, and caramelization breaks down the onion's own sugars. Both need time and moderate heat; high heat burns the outside before the inside has done anything. The tricks people use to speed it up all work by raising pH or adding sugar, and both give you brown onions that taste of neither reaction. There is no substitute for the slow route.</p>
    </div>
