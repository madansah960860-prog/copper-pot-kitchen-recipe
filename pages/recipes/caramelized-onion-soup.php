        <p class="ui mt4">Weights are what we actually used. Cup
          measures are converted from those weights rather than the other way round, which
          is the direction that survives.</p>
      </aside>
      <div>
        <h2>Method</h2>
        <ol class="method">
      <li><div><p>Melt the butter with the oil in your widest heavy pan over medium heat. Width matters more than depth here; a wide pan evaporates water faster and the onions brown instead of stewing.</p></div></li>
      <li><div><p>Add all the onions with the salt. They will fill the pan alarmingly. Stir to coat, put a lid on, and leave for ten minutes to collapse and release their water.</p></div></li>
      <li><div><p>Take the lid off, add the thyme, and turn the heat to medium-low. Now cook for eighty to ninety minutes, stirring every five or six minutes at first and every two or three toward the end.</p></div></li>
      <li><div><p>For the first half hour they will be pale and wet. Between thirty and sixty minutes they will turn straw-colored and start sticking. After an hour they go quickly, so pay attention: you are looking for a deep, even mahogany brown and a volume of perhaps a fifth of what you started with.</p></div></li>
      <li><div><p>Whenever a brown film builds on the base of the pan, add a splash of water and scrape it up. That film is flavor and you want it in the onions rather than welded to the pan. You will do this perhaps six or seven times.</p></div></li>
      <li><div><p>When the onions are properly dark and jammy, pour in the sherry. Let it bubble for two minutes, scraping the base once more.</p></div></li>
      <li><div><p>Add the stock. Bring to a simmer and cook, uncovered, for twenty minutes. Fish out the thyme stalks.</p></div></li>
      <li><div><p>Stir in the sherry vinegar, then taste. It will want salt and it will want pepper, and the vinegar is what stops the whole thing tasting flatly sweet.</p></div></li>
      <li><div><p>Heat the broiler. Toast the baguette slices on both sides, then rub one side of each with the cut garlic clove.</p></div></li>
      <li><div><p>Ladle the soup into four heatproof bowls. Float two croutons on each, pile the Gruyere on top, and broil for three or four minutes until the cheese is bubbling and browned in patches. Serve immediately and warn people that the bowls are extremely hot.</p></div></li>
        </ol>

        <h2>Notes</h2>
        <div class="note">
          <h3>Allergens</h3>
          <p>Contains milk (butter, Gruyere) and wheat (baguette). Contains sulphites from the sherry. Check the stock, which commonly contains celery and wheat.</p>
          <p><strong>Check every label yourself.</strong> Formulations change and this note
            describes the ingredients as written, not the packet in your hand.</p>
        </div>
        <div class="note mt5">
          <h3>Storage and reheating</h3>
          <p>The soup base, without the croutons, keeps four days in the refrigerator and freezes for three months. Do not freeze it with bread and cheese on top. Reheat to a full simmer, then make fresh croutons, which takes four minutes.</p>
        </div>
        <div class="note mt5">
          <h3>Swaps that work</h3>
          <p>Red onions give a sweeter, softer result. A mixture of yellow and a couple of shallots is very good. Comte or a decent Emmental stand in for Gruyere. A vegetarian version with a strong mushroom stock is genuinely good rather than a consolation.</p>
        </div>

