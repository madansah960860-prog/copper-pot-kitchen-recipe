      <div>
        <h2>Cooking by time available</h2>
        <p><strong>You have a whole Sunday.</strong> Beef shin ragu, and make the stock in a
          second pot while it is in the oven. Both are mostly waiting and they overlap
          perfectly.</p>
        <p><strong>You have an afternoon.</strong> Coq au vin or rogan josh. Both are around
          two and a half hours with about forty-five minutes of work.</p>
        <p><strong>You have a long evening and patience.</strong> The onion soup. Ninety
          minutes of onions is the longest stretch of continuous attention on this site.</p>
        <p><strong>You have tomorrow in mind.</strong> Braised red cabbage. Make it now, eat
          it then, and free your stovetop entirely on the day that matters.</p>
      </div>
      <div>
        <h2>Cooking by what is cheap</h2>
        <p>Nearly everything here uses a cut that costs a fraction of what the equivalent
          quick-cooking cut does, which is the quiet argument for slow cooking.</p>
        <p>Beef shin is a third the price of braising steak and considerably better for this.
          Lamb shoulder and neck are the two cheapest cuts in the case. Chicken legs cost less
          than half what breasts do and produce a far better braise. Carcasses for stock are
          frequently free if you ask.</p>
        <p>The one expensive thing on this site is the Gruyere on the onion soup, and a decent
          Emmental will do.</p>
      </div>
