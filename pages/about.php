    <div class="prose">
      <p>I cooked professionally for six years, which sounds more romantic than it was. Two
        years on garde manger in a hotel outside Boston, three on the line at a bistro in
        Providence that closed in 2016, and a final year running a very small kitchen in a
        bar where the menu was eleven items and none of them was mine.</p>
      <p>What I learned in those six years was mostly speed and consistency, which are the
        two things restaurant cooking is actually about and which translate badly to a home
        kitchen. What I did not learn, and had to work out afterward, was how to write down
        what I was doing so that somebody else could do it.</p>
      <p>That turns out to be a separate skill and a harder one. A line cook can produce a
        perfect braise and be entirely unable to tell you why, because the knowledge is in
        their hands and in fifteen hundred repetitions rather than in words. The first
        recipes I wrote were unusable. They said things like "until it looks right".</p>

      <h2>How a recipe gets onto this site</h2>
      <p>The same five stages every time, and the whole thing takes about a fortnight of
        evenings.</p>
      <ol>
        <li><strong>Cook it once, writing down what I actually did.</strong> Including the
          mistakes, which are usually the most useful notes. This pass produces a mess.</li>
        <li><strong>Cook it again with the scales out.</strong> Every single thing weighed in
          grams and milliliters. Cup measures are converted from those weights afterward,
          never the reverse, because converting in that direction is the one that survives
          contact with a different sized onion.</li>
        <li><strong>Cook it a third time following the written draft exactly.</strong> No
          improvising, no going from memory. This is where you find the step that was
          obvious in your head and absent from the page.</li>
        <li><strong>Give it to Rosa.</strong> Rosa Pardo lives next door, cooks well, and
          works from the draft with no verbal explanation from me. Her questions become the
          clarifications. She has sent more drafts back than she has approved and she is paid
          in dinner.</li>
        <li><strong>Check the numbers.</strong> Times, temperatures, yields, pan sizes, all
          checked against what was recorded rather than against memory.</li>
      </ol>
      <p>Only then does it go up. It is why there are six recipes on this site rather than
        two hundred, and it is the only thing about this operation I would defend at
        length.</p>

      <h2>Why slow cooking specifically</h2>
      <p>Partly because it is what I like eating. Mostly because it is the area where the
        internet is worst.</p>
      <p>A braise is difficult to write about honestly and easy to write about dishonestly. It
        takes hours, so a recipe that promises to do it in forty minutes will always get more
        clicks than one that tells you the truth, and the person who cooks the forty-minute
        version ends up with gray chewy meat and concludes that they cannot cook. They can. The
        recipe lied.</p>
      <p>The timing bar on every recipe here exists because of that specific problem. Four and
        a half hours sounds impossible until you can see that forty minutes of it is work and
        the rest is an oven doing something without you in the room.</p>

      <h2>The kitchen</h2>
      <p>Second floor of a building on Wickenden Street, in Fox Point, with a gas stove that
        is older than I am and an oven that runs about fifteen degrees cool, which I know and
        account for and which is why every temperature here is given with a visual cue as
        well.</p>
      <p>The copper is mostly inherited and mostly impractical. Everything that gets used
        daily is a heavy enameled cast iron casserole, one wide stainless pan, and a stockpot
        big enough to be slightly absurd.</p>

      <h2 id="photographs">A note on the photographs</h2>
      <p>The pictures on this site are licensed stock photography, not photographs of the
        food I cooked. I am a decent cook and a poor photographer, the kitchen faces north,
        and the honest choice was between bad pictures of the real thing and good pictures of
        something close to it.</p>
      <p>I have gone with the second, and I would rather say so plainly than let a caption
        imply otherwise. Every image is listed with its source and licence in the image
        credits file that ships with this site, at
        <code>assets/images/CREDITS.txt</code>.</p>
      <p>What this means practically: use the photographs to see roughly what a finished dish
        looks like, and use the written cues in the method to judge your own. Where a step
        matters, the recipe describes what to look for in words, which is more reliable than a
        photograph anyway.</p>

      <h2>Money</h2>
      <p>This site is paid for by display advertising, in the slots marked "Advertisement" in
        the layout. That is the whole business model. There are no sponsored recipes, no paid
        placements, no affiliate links at present, and nothing for sale. If any of that
        changes it will be disclosed on the page it affects as well as in the
        <a href="../policies/advertising-disclosure.php">advertising disclosure</a>.</p>
      <p>Nobody has ever paid to be mentioned here and nobody is going to.</p>
