<h1>Privacy Policy</h1>
<p class="lede">This page explains, in ordinary language, what happens to information when you visit Copper Pot Kitchen at www.copperpotkitchen.com. We have tried to write it the way we would explain it to somebody standing in front of us, rather than in the register of a contract nobody reads.</p>
<p class="stamp">Last updated 1 September 2026. This policy covers www.copperpotkitchen.com and every page beneath it.</p>

<h2>Who is responsible for this site</h2>
<p>Copper Pot Kitchen is operated by Gil Mercer, cook, writer and sole proprietor, working from Providence, Rhode Island. The mailing address for correspondence appears on the contact page and again at the foot of this policy. For anything touching privacy, data protection or the removal of information, write to <a href="mailto:privacy@copperpotkitchen.com">privacy@copperpotkitchen.com</a> and the message will reach a person rather than a ticket queue.</p>

<h2>What information we collect</h2>
<p>We deliberately collect as little as we can while still running a working website. In practice the information involved falls into four groups.</p>
<ul>
  <li><strong>Information you type and send us.</strong> If you email us, or complete the inquiry form on the contact page, we receive whatever you chose to put in it: your name, your email address, and the content of your message. If you tell us about an allergy or an intolerance while asking about a recipe, that detail is used to answer your question and nothing else.</li>
  <li><strong>Technical information collected automatically.</strong> Server log data, described in the next section.</li>
  <li><strong>Cookie and device information used for advertising and measurement.</strong> Set by third parties rather than by us, and described under advertising below.</li>
  <li><strong>Nothing else.</strong> We do not ask for dates of birth, we do not request identity documents, there is no membership system on this website, and no payment is taken through it.</li>
</ul>

<h2>Log files</h2>
<p>Like effectively every site on the web, our hosting provider keeps server log files. These record the internet protocol address of the requesting device, the browser type and version, the operating system, the date and time of the request, the pages requested and the referring page. Log entries are not linked by us to anything that identifies you by name. They are used to diagnose faults, to understand which pages are being read, and to identify automated abuse.</p>

<h2>Cookies</h2>
<p>A cookie is a small text file that a website asks your browser to store and hand back on later visits. Copper Pot Kitchen sets no cookies of its own for tracking purposes. Cookies that do appear while you are reading these pages are placed by the third-party services described below. A fuller account, including how to switch cookies off in each major browser, is in our <a href="cookie-policy.php">Cookie Policy</a>.</p>

<h2>Third-party vendors and advertising</h2>
<p>This site carries display advertising, and the advertising slots reserved in the layout are filled by advertising technology operated by other companies. Those companies may use cookies, web beacons, device identifiers and similar technologies to select and to measure the advertisements shown to you.</p>
<p>Google, as a third-party vendor, uses cookies to serve advertisements on this site. Google's use of the DoubleClick DART cookie enables it and its partners to serve advertisements to users based on their visit to this site and to other sites on the internet. Users may opt out of the use of the DART cookie by visiting the Google advertising and content network privacy policy linked below.</p>
<p>Third-party ad servers and ad networks use technology in the advertisements and links that appear on www.copperpotkitchen.com and send a signal directly to your browser. When this happens they automatically receive your IP address. These technologies are used to measure the effectiveness of advertising campaigns and to personalize the advertising content that you see. Copper Pot Kitchen has no access to, and no control over, the cookies used by third-party advertisers.</p>
<p>You should consult the respective privacy policies of these third-party ad servers for more detailed information on their practices and for instructions about opting out of them. The policy you are reading does not apply to, and we cannot control the activities of, other advertisers or other websites.</p>

<h2>How to opt out of personalized advertising</h2>
<ul>
  <li>Visit <a href="https://adssettings.google.com/" rel="nofollow noopener" target="_blank">Google Ads Settings</a> to turn off ad personalization on Google services and on sites that use Google advertising.</li>
  <li>Visit <a href="https://optout.aboutads.info/" rel="nofollow noopener" target="_blank">optout.aboutads.info</a>, operated by the Digital Advertising Alliance, to opt out of interest-based advertising from many companies at once.</li>
  <li>Visit <a href="https://www.youronlinechoices.com/" rel="nofollow noopener" target="_blank">Your Online Choices</a> for the equivalent European tool.</li>
  <li>Visit the <a href="https://policies.google.com/technologies/ads" rel="nofollow noopener" target="_blank">Google advertising and content network privacy policy</a> for the DoubleClick DART cookie opt-out described above.</li>
  <li>Switch third-party cookies off in your browser, or install a reputable content blocker. Advertising will still appear, but it will be chosen without reference to your browsing history.</li>
</ul>
<p>Opting out stops personalization. It does not stop advertisements and it does not reduce how many of them you see.</p>

<h2>Your rights under the GDPR</h2>
<p>If you are in the United Kingdom or the European Economic Area, data protection law gives you a set of rights over personal data relating to you. You have the right to be informed about how your data is used, which is the purpose of this document. You have the right of access, meaning you may ask for a copy of any personal data we hold about you. You have the right to rectification if that data is wrong, and the right to erasure where we have no overriding reason to keep it. You have the right to restrict processing, the right to data portability, and the right to object to processing carried out on the basis of legitimate interests, including profiling for advertising purposes.</p>
<p>Where we rely on a lawful basis it is normally your consent, gathered through the consent notice shown by our advertising partners, or our legitimate interest in keeping a website running and secure, which covers server logs. To exercise any right, email <a href="mailto:privacy@copperpotkitchen.com">privacy@copperpotkitchen.com</a>. We answer within one calendar month. You also have the right to complain to your national supervisory authority.</p>

<h2>Your rights under the CCPA and CPRA</h2>
<p>California residents have the right to know what categories of personal information have been collected about them, the right to know whether personal information is sold or shared and to opt out of that sale or sharing, the right to request deletion, the right to correct inaccurate information, and the right not to be treated differently for exercising any of these rights.</p>
<p>Copper Pot Kitchen does not sell personal information for money. Advertising technology that we do not control may nonetheless amount to "sharing" for cross-context behavioral advertising under California law. The opt-out links above are the effective route to stopping that, and requests may also be sent to <a href="mailto:privacy@copperpotkitchen.com">privacy@copperpotkitchen.com</a> with "California privacy request" in the subject line.</p>

<h2>Children's privacy</h2>
<p>Protecting the privacy of children is a priority we take seriously. Copper Pot Kitchen does not knowingly collect any personally identifiable information from children under the age of 13, and this site is not directed at children. In line with the Children's Online Privacy Protection Act, if you believe a child has provided personal information through this website, contact us at <a href="mailto:privacy@copperpotkitchen.com">privacy@copperpotkitchen.com</a> and we will make our best efforts to remove that information promptly.</p>
<p>Recipes on this site are written for the adult doing the cooking. Where a dish is suitable to make with children, the supervision required is stated inside the method itself rather than assumed.</p>

<h2>How long information is kept</h2>
<p>Email correspondence is retained for as long as it remains useful and then deleted, normally within twenty-four months. Server logs are rotated by our hosting provider and are typically discarded after ninety days. Cookies set by third parties expire on their own schedules, which are documented in their policies rather than in ours.</p>

<h2>Security</h2>
<p>This site is served over an encrypted HTTPS connection. Access to the hosting account is protected by a strong unique password and two-factor authentication. No transmission over the internet is ever completely secure and we cannot promise absolute safety, but we do not ask you for information we do not need, which remains the most reliable protection available to anybody.</p>

<h2>Changes to this policy</h2>
<p>If this policy changes, the revised version appears on this page with a new date at the top, together with a short line explaining what changed, so that readers who have already been through it once do not have to compare two documents line by line.</p>

