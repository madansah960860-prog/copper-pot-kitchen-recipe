        <h2>What this site is</h2>
        <p>Six recipes. Not six hundred. Each one has been cooked here at least three times,
          weighed on the second pass, and then handed to somebody else to cook from the
          written draft with no verbal explanation, which is how you find the step that made
          sense only inside the cook's own head.</p>
        <p>They are all slow. Not because slow is virtuous, but because the things that
          genuinely reward time, a shin of beef, a pot of stock, an hour and a half of
          onions, are exactly the things that most recipe sites hurry along with a promise of
          a twenty-five-minute shortcut that does not work.</p>
        <p>There is no story before the recipe. The headnote is three sentences and then the
          ingredients start.</p>
      </div>
      <div>
        <h2>Two things every recipe carries</h2>
        <p><strong>A note on why it works.</strong> Not a history, and not a paragraph about
          a grandmother. The actual mechanism: what the collagen is doing, why the vinegar
          keeps the cabbage red, why the yogurt splits if you add it to a hot pan. If we
          cannot explain a step, we take it out.</p>
        <p><strong>A timing bar.</strong> Drawn to scale, showing hands-on time against
          waiting. The beef shin ragu takes four and a half hours and forty minutes of that
          is work. That distinction decides whether you cook something on a Sunday, and it
          is almost never published.</p>
