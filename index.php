      <div>
        <h2>Some plain statements about cooking</h2>
        <p><strong>Brown the meat properly or do not bother.</strong> Fifteen minutes of
          real browning, in batches, in a pan that is hot enough, is the difference between a
          braise that tastes of something and one that tastes of stewed liquid. Every recipe
          here that starts with browning says how long it should take, and that number is not
          optimistic.</p>
        <p><strong>Salt earlier and more than you think.</strong> Most home cooking is
          undersalted, and the fix is not a heavier hand at the table but seasoning at each
          stage. Salt the onions when they go in. Taste at the end and then add more.</p>
        <p><strong>Acid at the end fixes a flat dish.</strong> A teaspoon of vinegar or a
          squeeze of lemon in something that tastes dull is right more often than more salt
          is. The onion soup on this site has a tablespoon of sherry vinegar in it for
          exactly this reason.</p>
        <p><strong>Timings are a guide; your eyes are the instrument.</strong> Every oven
          lies by twenty degrees in one direction or another, every stovetop has a different
          maximum, and a wide pan reduces twice as fast as a narrow one. Where a step has a
          visual cue, follow the cue rather than the clock.</p>
        <p><strong>Most braises are better the next day.</strong> Not a folk belief. Time in
          the refrigerator lets fat solidify so you can lift it off, gives starches time to
          swell, and lets flavors that are volatile settle into the liquid. Cook the ragu on
          Saturday and eat it on Sunday.</p>
      </div>
